import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {SalesStore} from '../agent/lib/pancake/store.ts';
import type {SqlDatabase,SqlSession} from '../agent/lib/pancake/database.ts';
import {normalizeOrder} from '../agent/lib/pancake/normalize.ts';
const raw=(updated='2026-11-14T02:00:00Z')=>normalizeOrder({id:1,shop_id:20,status:1,inserted_at:'2026-11-14T01:00:00Z',updated_at:updated,items:[]},20,'VND');
test('real SQL migration, scoped order upserts, durable page checkpoints and lease isolation',async()=>{
 const pg=new PGlite();
 const db:SqlDatabase={query:(text,values)=>pg.query(text,values as unknown[]),transaction:fn=>pg.transaction(tx=>fn({query:(text,values)=>tx.query(text,values as unknown[])} as SqlSession))};
 const store=new SalesStore(db);await store.init();await store.init();
 const input={connectionId:'pos',shopId:'20',currency:'VND',from:'2026-11-07T00:00:00Z',to:'2026-11-14T03:00:00Z'};
 const id=await store.enqueue(input);assert.equal(await store.enqueue(input),id);
 const job=await store.claim('pos','20');assert(job);assert.equal(await store.claim('pos','20'),null);
 await assert.rejects(store.checkpoint({...job,lease:'wrong'},[raw()],2));
 await store.checkpoint(job,[raw()],2);
 assert.equal((await store.status('pos','20')).completeThrough,null);
 const next=await store.claim('pos','20');assert(next);assert.equal(next.page,2);await store.finish(next,[raw('2026-11-14T03:00:00Z')]);
 await store.upsert('pos',[raw()]);
 assert.equal((await store.orders('pos','20','2026-11-07','2026-11-14'))[0].updatedAt,'2026-11-14T03:00:00.000Z');
 assert.equal((await store.orders('other','20','2026-11-07','2026-11-14')).length,0);
 assert.equal((await store.status('pos','20')).completeThrough,'2026-11-14T03:00:00.000Z');
 const equalVersion={...raw('2026-11-14T03:00:00Z'),status:5};await store.upsert('pos',[equalVersion]);
 assert.equal((await store.status('pos','20')).pendingEvents,1);
 const event=(await store.events('pos','20'))[0];assert(event);
 await store.acknowledge('pos','20',event.orderId,event.receivedAt,equalVersion);
 assert.equal((await store.events('pos','20')).length,0);
 assert.equal((await store.orders('pos','20','2026-11-07','2026-11-14'))[0].status,5);
 await pg.close();
});
